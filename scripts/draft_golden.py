"""Draft candidate QA pairs from sampled corpus chunks (step 1 of building the golden set).

Each candidate is generated by an LLM *from one specific chunk*, so its gold source
(NTRS id + page) is known by construction. Candidates are then reviewed by hand
(scripts/finalize_golden.py records which were kept / edited / dropped) — the LLM output
is never used unreviewed. Uses a different model (qwen) from the answer generator
(gpt-oss-20b) to reduce self-preference.

Usage: python scripts/draft_golden.py --n 70 --seed 7 --out eval/candidates.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from marsrag.config import get_settings  # noqa: E402
from marsrag.ingest import load_chunks  # noqa: E402
from marsrag.llm import ChatClient, Provider  # noqa: E402

PROMPT = """You write evaluation questions for a question-answering system over NASA technical reports \
about human Mars missions.

Below is one excerpt from the report "{title}" (page {page}).
Write ONE question that:
- can be answered completely and specifically from this excerpt alone (a number, name, design choice, or a short reason);
- makes sense to someone who has NOT seen the excerpt (do not say "the excerpt", "this paper", "the authors", "the study"; name the specific system/mission instead);
- is about Mars mission engineering, radiation, life support, spacecraft design, EDL, crew health, ISRU or mission planning.
If the excerpt is a reference list, table of contents, acknowledgements or too vague for a specific question, output {{"skip": true}}.

Return only JSON: {{"question": "...", "answer": "short answer copied/paraphrased from the excerpt", "evidence": "exact short quote from the excerpt"}}

Excerpt:
\"\"\"{text}\"\"\""""


def good_chunk(text: str) -> bool:
    words = text.split()
    if len(words) < 120:
        return False
    low = text.lower()
    if low.count("et al") > 2 or low.count("doi") > 1 or "references" in low[:60]:
        return False
    return bool(re.search(r"\d", text))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=70)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--model", default="qwen/qwen3.8-27b")
    ap.add_argument("--out", default="eval/candidates.jsonl")
    ap.add_argument("--exclude", default="", help="jsonl of candidates whose chunks must not be reused")
    args = ap.parse_args()

    s = get_settings()
    chunks = [c for c in load_chunks(s.chunks_path) if good_chunk(c.text)]
    excluded = set()
    if args.exclude and Path(args.exclude).exists():
        excluded = {json.loads(line)["source_chunk_id"] for line in open(args.exclude) if line.strip()}
    by_doc = defaultdict(list)
    for c in chunks:
        if c.chunk_id not in excluded:
            by_doc[c.doc_id].append(c)
    rng = random.Random(args.seed)
    docs = sorted(by_doc)
    rng.shuffle(docs)
    picked = []
    # one chunk per document first (coverage), then a second round
    for rnd in range(3):
        for d in docs:
            if len(picked) >= args.n:
                break
            pool = by_doc[d]
            if len(pool) > rnd:
                picked.append(rng.choice(pool))
    client = ChatClient(args.model, [Provider("groq", s.llm_base_url, s.llm_key_env)],
                        cache_path=s.cache_dir / "llm_cache.sqlite", max_tokens=1200)
    out = Path(args.out)
    done = set()
    if out.exists():
        done = {json.loads(line)["source_chunk_id"] for line in out.open() if line.strip()}
    with out.open("a") as f:
        for i, c in enumerate(picked):
            if c.chunk_id in done:
                continue
            msg = PROMPT.format(title=c.title, page=c.page, text=c.text)
            try:
                resp = client.chat([{"role": "user", "content": msg}])
            except Exception as e:  # noqa: BLE001
                print(f"stop at {i}: {e}")
                break
            txt = re.sub(r"<think>.*?</think>", "", resp.text, flags=re.S).strip()
            m = re.search(r"\{.*\}", txt, flags=re.S)
            try:
                data = json.loads(m.group(0)) if m else {"skip": True}
            except json.JSONDecodeError:
                data = {"skip": True}
            rec = {"source_chunk_id": c.chunk_id, "doc_id": c.doc_id, "page": c.page, "title": c.title,
                   "topic": c.topic, **data}
            f.write(json.dumps(rec) + "\n")
            f.flush()
            print(i, c.chunk_id, (data.get("question") or "SKIP")[:100])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
