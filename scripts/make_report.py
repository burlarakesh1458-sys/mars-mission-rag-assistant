"""Render reports/RESULTS.md (tables + worked / failed examples) from the JSON results.
Every number in the README comes from this file's output."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from marsrag.eval.metrics import citation_correct, load_jsonl  # noqa: E402

R = ROOT / "reports"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ms(x):
    return "n/a" if x is None or x != x else f"{x:,.0f} ms"


def main() -> int:
    out = ["# Evaluation results", "", "Generated by `scripts/make_report.py` from the JSON files in `reports/`.", ""]
    ret = json.loads((R / "retrieval_eval.json").read_text()) if (R / "retrieval_eval.json").exists() else None
    if ret:
        out += [f"## Retrieval ablation ({ret['n_questions']} answerable golden questions, {ret['n_chunks']} chunks)", "",
                "| Retriever | page hit@1 | page hit@5 | page MRR@10 | doc hit@1 | doc hit@5 | latency p50 | latency p95 |",
                "|---|---|---|---|---|---|---|---|"]
        for name, v in ret["configs"].items():
            m = v["metrics"]
            out.append(f"| {name} | {pct(m['page_hit@1'])} | {pct(m['page_hit@5'])} | {m['page_mrr@10']:.3f} | "
                       f"{pct(m['doc_hit@1'])} | {pct(m['doc_hit@5'])} | {ms(m['latency_ms_p50'])} | {ms(m['latency_ms_p95'])} |")
        out.append("")
    e2e = json.loads((R / "e2e_eval.json").read_text()) if (R / "e2e_eval.json").exists() else {}
    if e2e:
        out += ["## End-to-end (50 golden questions: 40 answerable, 10 unanswerable)", "",
                "| Metric | " + " | ".join(e2e) + " |", "|---|" + "---|" * len(e2e)]
        rows = [("Refusal accuracy (all 50)", "refusal_accuracy", pct),
                ("Unanswerable correctly declined", "unanswerable_declined_rate", pct),
                ("Answerable wrongly declined", "answerable_false_refusal_rate", pct),
                ("Answered with >=1 citation", "citation_present_rate", pct),
                ("Citation accuracy, report level (answered)", "citation_accuracy_doc", pct),
                ("Citation accuracy, page level (answered)", "citation_accuracy_page", pct),
                ("Latency p50, retrieval", "latency_retrieve_ms_p50", ms),
                ("Latency p95, retrieval", "latency_retrieve_ms_p95", ms),
                ("Latency p50, end-to-end", "latency_total_ms_p50", ms),
                ("Latency p95, end-to-end", "latency_total_ms_p95", ms),
                ("Latency p50, LLM call", "latency_llm_ms_p50", ms),
                ("Latency p95, LLM call", "latency_llm_ms_p95", ms)]
        for label, key, f in rows:
            out.append(f"| {label} | " + " | ".join(f(v.get(key)) for v in e2e.values()) + " |")
        out.append("")
    rag = json.loads((R / "ragas_eval.json").read_text()) if (R / "ragas_eval.json").exists() else {}
    for cfg, v in rag.items():
        out += [f"## Ragas ({cfg}; judge `{v['judge_model']}`)", "", "| Metric | mean | n |", "|---|---|---|"]
        for k in ("llm_context_precision", "llm_context_recall", "faithfulness",
                  "nonllm_context_precision", "nonllm_context_recall"):
            m = v.get(k) or {}
            out.append(f"| {k} | {'n/a' if m.get('mean') is None else f'{m['mean']:.3f}'} | {m.get('n', 0)} |")
        out.append("")
    ans_path = R / "answers_rerank.jsonl"
    if ans_path.exists():
        rows = load_jsonl(ans_path)
        good, bad = [], []
        for r in rows:
            if r["answerable"]:
                ok = (not r["refused"]) and citation_correct(r["citations"], r, "page")
            else:
                ok = r["refused"]
            (good if ok else bad).append(r)
        out += [f"## Examples (config `rerank`): {len(good)} correct, {len(bad)} not", ""]

        def show(r):
            lines = [f"**{r['id']}. {r['question']}**", ""]
            lines.append(f"- Expected: {r['reference'] or 'decline (not in the reports)'}"
                         + (f" (gold: NTRS {r['gold_doc_id']} p. {r['gold_pages']})" if r["answerable"] else ""))
            lines.append(f"- Got: {'DECLINED (' + str(r['refusal_reason']) + ')' if r['refused'] else r['answer']}")
            for c in r["citations"]:
                lines.append(f"  - [{c['n']}] {c['title']}, p. {c['page']} — {c['url']}")
            if r["contexts"] and r["contexts"][0].get("rerank_score") is not None:
                lines.append(f"- Top rerank score: {r['contexts'][0]['rerank_score']:.2f}")
            return lines + [""]

        out += ["### Worked", ""]
        picks = [r for r in good if r["answerable"]][:4] + [r for r in good if not r["answerable"]][:2]
        for r in picks:
            out += show(r)
        out += ["### Failed (all failures listed)", ""]
        for r in bad:
            out += show(r)
    (R / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out[:80]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
